const BOUNDS = { minLon: 16.3, maxLon: 32.9, minLat: -34.9, maxLat: -22.0 };
const LON_SCALE = Math.cos((29 * Math.PI) / 180);
const UNIT = 40;

export const SA_MAP_WIDTH = Math.round(
  (BOUNDS.maxLon - BOUNDS.minLon) * LON_SCALE * UNIT,
);
export const SA_MAP_HEIGHT = Math.round((BOUNDS.maxLat - BOUNDS.minLat) * UNIT);

export function projectToSaMap(longitude: number, latitude: number) {
  return {
    x: (longitude - BOUNDS.minLon) * LON_SCALE * UNIT,
    y: (BOUNDS.maxLat - latitude) * UNIT,
  };
}

const ringPath = (ring: [number, number][]) =>
  ring
    .map(([lon, lat], i) => {
      const { x, y } = projectToSaMap(lon, lat);
      return `${i === 0 ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`;
    })
    .join("") + "Z";

/** Outline with Lesotho cut out; render with fill-rule="evenodd". */
export const SA_OUTLINE_PATH = ringPath(OUTLINE) + ringPath(LESOTHO);
